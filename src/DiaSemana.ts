/**
 * Representa los días de la semana utilizados para la planificación, 
 * aplicación de descuentos especiales y control de horarios en el sistema.
 * 
 * @enum {string}
 * @readonly
 */
export enum DiaSemana {
    /** Día lunes. */
    LUNES,

    /** Día martes. */
    MARTES,

    /** Día miércoles. */
    MIERCOLES,

    /** Día jueves. */
    JUEVES,

    /** Día viernes. */
    VIERNES,

    /** Día sábado. */
    SABADO,

    /** Día domingo. */
    DOMINGO
}