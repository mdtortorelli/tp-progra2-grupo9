/**
 * Representa las diferentes categorías en las que se pueden clasificar 
 * los productos dentro del sistema.
 * 
 * @enum {string}
 * @readonly
 */
export enum CategoriaProd {
    /** Categoría correspondiente a cortes y platos elaborados con carne. */
    CARNE,

    /** Categoría correspondiente a ensaladas y opciones de vegetales frescos. */
    ENSALADA,

    /** Categoría correspondiente a bebidas. */
    BEBIDA,

    /** Categoría correspondiente a postres y opciones dulces. */
    POSTRE
}